// Regenerate with Node from the twelve downloaded English 1948 Saka monthly pages:
// https://packolkata.imd.gov.in/panchang/en/panchang
// Printed edition: https://packolkata.imd.gov.in/download/EnglishRP2627.zip
// Archive SHA-256: fe3cb9fc27647fafc92cedfab3e25d53d19bbfb49e4949a8436312641174a835
// node scripts/import-imd-panchanga.mjs <html-directory> > src/core/calendar/indian-panchanga-data.ts
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { join } from "node:path";

const directory = process.argv[2];
assert.ok(directory, "Supply the directory of monthly pages saved as <slug>.html.");
const pages = [
  "chaitra", "vaishaka", "jyaishtha", "ashadha", "sravana", "bhadra",
  "asvina", "kartika", "agrahayana", "pausha", "magha", "phalguna",
];
const names = [
  "Pratipad", "Dvitiya", "Tritiya", "Chaturthi", "Panchami", "Shashthi", "Saptami",
  "Ashtami", "Navami", "Dasami", "Ekadasi", "Dvadasi", "Trayodasi", "Chaturdasi",
];
const stamp = new Intl.DateTimeFormat("en-US", { month: "long", day: "numeric", timeZone: "UTC" });
const lines = [
  "// Generated by scripts/import-imd-panchanga.mjs from the IMD Rashtriya Panchang, 1948 Saka.",
  "// One value per Gregorian day, starting 2026-03-22: 1–15 waxing and 16–30 waning.",
  "export const SUNRISE_TITHIS: readonly number[] = Object.freeze([",
];
let date = Date.UTC(2026, 2, 22);
let previous;
for (const page of pages) {
  const source = await readFile(join(directory, page + ".html"), "utf8");
  const rows = source.split(/<div class="fw-bold">Day \d+<\/div>/u).slice(1);
  assert.equal(rows.length, ["vaishaka", "jyaishtha", "ashadha", "sravana", "bhadra"].includes(page) ? 31 : 30, page);
  const start = new Date(date).toISOString().slice(0, 10);
  const values = [];
  for (const row of rows) {
    const day = /<small class="text-warning">([^<]+)<\/small>/u.exec(row)?.[1];
    const julian = /<strong>Julian Day:<\/strong>\s*([\d.]+)<\/p>/u.exec(row)?.[1];
    assert.equal(day?.trim(), stamp.format(date));
    assert.equal(Number(julian), date / 86_400_000 + 2_440_587.5);
    // The first tithi is active at sunrise. A second entry after "then" begins later.
    const tithi = /<strong>Tithi:<\/strong>\s*\([^)]+ (Sukla|Krishna)\) (\w+)/u.exec(row);
    assert.ok(tithi, day);
    const [, half, name] = tithi;
    let number = names.indexOf(name) + 1;
    if (name === (half === "Sukla" ? "Purnima" : "Amavasya")) number = 15;
    assert.ok(number > 0, tithi[0]);
    if (half === "Krishna") number += 15;
    if (previous !== undefined) assert.ok((number - previous + 30) % 30 <= 2, day);
    previous = number;
    values.push(number);
    date += 86_400_000;
  }
  lines.push(`  // ${start} · ${page}`, `  ${values.join(", ")},`);
}
assert.equal(date, Date.UTC(2027, 2, 22));
console.log([...lines, "]);"].join("\n"));
